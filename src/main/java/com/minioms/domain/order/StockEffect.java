package com.minioms.domain.order;

/**
 * 受注のステータス遷移が在庫に与える影響。
 *
 * <p>Why not: 影響の判断を在庫側やユースケースに持たせない。「いつ引き当て、いつ解除し、
 * いつ実在庫から落とすか」は受注ライフサイクルの業務ルールであり、
 * 状態機械から導かれる。外に置くと遷移を追加したときに更新が漏れる。</p>
 */
public enum StockEffect {

    /** 在庫は動かない */
    NONE,
    /** 出荷を約束する(引当済を増やす) */
    ALLOCATE,
    /** 約束を取り消す(引当済を戻す) */
    RELEASE,
    /** 約束を果たす(実在庫と引当済の両方を減らす) */
    SHIP_OUT
}
