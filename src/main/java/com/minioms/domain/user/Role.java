package com.minioms.domain.user;

/**
 * 利用者の操作権限。
 *
 * <p>Why not: 機能ごとの権限フラグ(受注確認可・出荷指示可・在庫参照可…)にしない。
 * OMSの運用で実際に引かれる線は「見るだけの人」と「動かす人」の1本であり、
 * 機能ごとに持つと組み合わせが増えるだけで、誰が何をできるかが読めなくなる。</p>
 */
public enum Role {

    /** 受注と在庫を動かせる。倉庫への出荷指示など、システムの外に影響が出る操作を行う */
    OPERATOR,

    /** 参照のみ。誤操作で在庫や出荷が動くことを防ぐ */
    VIEWER
}
